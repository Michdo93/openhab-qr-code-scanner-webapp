def get_ip():
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        s.connect(('10.255.255.255', 1))
        IP = s.getsockname()[0]
    except Exception:
        IP = '127.0.0.1'
    finally:
        s.close()
    return IP

@app.route('/')
def index():
    device_key = request.args.get('device')
    oh_id = DEVICE_MAP.get(device_key)
    
    # URL sauber zusammenbauen
    if oh_id:
        target_url = f"{OPENHAB_BASE}?sitemap={SITEMAP_NAME}&w={oh_id}"
    else:
        target_url = f"{OPENHAB_BASE}?sitemap={SITEMAP_NAME}"

    return render_template('index.html', 
                           target_url=target_url,
                           device_key=device_key)

